# Base maps from gen-indo-aryan-1.ts
BASE_IA1 = BASE['indo_aryan_1']
BASE_BN_MR = BASE['bn_mr_gu_pa']

def merge_and_build(code, native_name, specific_dict, base_name=None):
    t = {}
    base_dict = BASE_IA1.get(base_name, {}) if base_name else {}
    alt_base = BASE_BN_MR.get(base_name, {}) if base_name else {}
    
    # Priority: specific_dict -> alt_base -> base_dict -> HI
    for k in ALL_KEYS:
        if k in specific_dict and specific_dict[k]:
            t[k] = specific_dict[k]
        elif k in alt_base and alt_base[k]:
            t[k] = alt_base[k]
        elif k in base_dict and base_dict[k]:
            t[k] = base_dict[k]
        else:
            t[k] = HI.get(k, '')
            
    write_locale(code, native_name, t)

